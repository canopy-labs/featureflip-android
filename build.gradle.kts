// The SDK reports its version in the User-Agent (#4141). publish-android-sdk.yml seds the
// `version` above from the release tag, so generating SDK_VERSION from it keeps the two
// in step instead of duplicating it in source, where it would drift (#2141).
val generateSdkVersion by tasks.registering {
    val sdkVersion = project.version.toString()
    val outDir = layout.buildDirectory.dir("generated/sdkVersion")
    inputs.property("version", sdkVersion)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("dev/featureflip/android/SdkVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            "// Generated by build.gradle.kts from `version` (#4141). Do not edit.\n" +
                "package dev.featureflip.android\n\n" +
                "internal const val SDK_VERSION = \"$sdkVersion\"\n",
        )
    }
}

